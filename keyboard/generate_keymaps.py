"""Regenerate basic USB keymaps: python keyboard/generate_keymaps.py ../qmk_firmware."""
import pathlib
import re
import sys

qmk = pathlib.Path(sys.argv[1])
codes = (qmk / "quantum/keycodes.h").read_text(encoding="utf-8")
values = {k: int(v, 16) for k, v in re.findall(r"(KC_\w+)\s*=\s*(0x[0-9A-Fa-f]+)", codes)}
aliases = dict(re.findall(r"^\s*(KC_\w+)\s*=\s*(KC_\w+)", codes, re.M))
aliases.update(dict(re.findall(r"^#define\s+(JP_\w+)\s+(KC_\w+)", (qmk / "quantum/keymap_extras/keymap_japanese.h").read_text(encoding="utf-8"), re.M)))


def usage(code):
    if code == "MO(_FN)":
        return "FN"
    while code in aliases:
        code = aliases[code]
    # Consumer/system controls and vendor actions are intentionally omitted.
    value = values.get(code, 0)
    return f"0x{value:02x}" if value <= 0x73 or 0x87 <= value <= 0x8B or 0xE0 <= value <= 0xE7 else "0x00"


output = ["// Matrix positions and default layouts from QMK keyboards/framework.",
          "// Copyright 2022-2023 Framework Computer", "// SPDX-License-Identifier: GPL-2.0-or-later",
          "// Generated by keyboard/generate_keymaps.py; values are USB keyboard usages.",
          "use super::Keymap;", '#[cfg(any(feature = "ansi", feature = "iso", feature = "jis", test))]', "use super::FN;", ""]
for variant in ("ansi", "iso", "jis", "numpad", "macropad"):
    directory = qmk / "keyboards/framework" / variant
    header = (directory / f"{variant}.h").read_text(encoding="utf-8").replace("\\\n", "")
    params, body = re.search(r"#define LAYOUT\((.*?)\)\s*\{(.*)", header, re.S).groups()
    params = [p.strip() for p in params.split(",")]
    source = (directory / "keymaps/default/keymap.c").read_text(encoding="utf-8")
    layer = "_BASE" if variant in ("ansi", "iso", "jis") else "_NUMLOCK"
    keys = re.search(r"\[" + layer + r"\]\s*=\s*LAYOUT\((.*?)\n\s*\)", source, re.S).group(1)
    keys = [k.strip() for k in keys.split(",")]
    assert len(params) == len(keys), (variant, len(params), len(keys))
    mapping = dict(zip(params, keys))
    output += [f'#[cfg(any(feature = "{variant}", test))]', "#[rustfmt::skip]", f"pub const {variant.upper()}: Keymap = ["]
    rows = re.findall(r"\{([^{}]+)\}", body.split("\nenum")[0])
    assert len(rows) == (8 if variant in ("ansi", "iso", "jis") else 4)
    for row in rows:
        positions = [p.strip() for p in row.split(",") if p.strip()]
        mapped = [mapping.get(p, "KC_NO") for p in positions]
        output += ["    // " + ", ".join(mapped), "    [" + ", ".join(usage(k) for k in mapped) + (", 0x00" * (16 - len(mapped))) + "],"]
    output += ["    [0; 16],"] * (8 - len(rows))
    output += ["];", ""]
pathlib.Path(__file__).with_name("src").joinpath("layouts.rs").write_text("\n".join(output))
